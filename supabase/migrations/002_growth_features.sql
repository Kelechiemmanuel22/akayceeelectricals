create or replace function public.subscribe_newsletter(subscriber_email text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if subscriber_email is null or subscriber_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then
    raise exception 'Please enter a valid email address.';
  end if;
  insert into newsletter_subscribers(email, status, consent_at)
  values (lower(trim(subscriber_email)), 'confirmed', now())
  on conflict (lower(email)) do update set status = 'confirmed', consent_at = now(), unsubscribed_at = null;
end; $$;
grant execute on function public.subscribe_newsletter(text) to anon, authenticated;

create or replace function public.unsubscribe_newsletter(subscriber_email text)
returns void language plpgsql security definer set search_path = public as $$
begin
  update newsletter_subscribers set status = 'unsubscribed', unsubscribed_at = now()
  where lower(email) = lower(trim(subscriber_email));
end; $$;
grant execute on function public.unsubscribe_newsletter(text) to anon, authenticated;

