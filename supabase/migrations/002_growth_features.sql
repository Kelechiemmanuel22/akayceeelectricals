-- Customer engagement, newsletter and privacy-conscious analytics.
create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('page_view','product_view','whatsapp_click','search','quote_started','quote_sent','newsletter_signup','callback_request')),
  page_path text not null default '/',
  product_slug text,
  category_id text,
  search_term text,
  metadata jsonb not null default '{}'::jsonb,
  session_id text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  status text not null default 'confirmed' check (status in ('confirmed','unsubscribed','suppressed')),
  consent_at timestamptz not null default now(),
  unsubscribed_at timestamptz,
  source text not null default 'website',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists newsletter_email_unique on public.newsletter_subscribers (lower(email));

create table if not exists public.newsletter_campaigns (
  id uuid primary key default gen_random_uuid(),
  subject text not null,
  preview_text text not null default '',
  headline text not null,
  body text not null,
  button_label text,
  button_url text,
  image_url text,
  status text not null default 'draft' check (status in ('draft','sending','sent','failed')),
  recipient_count integer not null default 0,
  sent_at timestamptz,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_requests (
  id uuid primary key default gen_random_uuid(),
  request_type text not null check (request_type in ('quote','callback','product_help')),
  name text not null,
  phone text not null,
  email text,
  details text not null default '',
  delivery_area text,
  preferred_time text,
  items jsonb not null default '[]'::jsonb,
  status text not null default 'new' check (status in ('new','contacted','completed','closed')),
  admin_notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  message text not null,
  button_label text not null default 'Explore catalogue',
  button_url text not null default '/products',
  active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.buying_guides (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  summary text not null,
  content text not null,
  image_url text,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

