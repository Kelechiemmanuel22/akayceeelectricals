import { useCatalog } from '../context/CatalogContext'

export function BrandLogo({
  brand,
  logo,
  logoDark,
  className = '',
  variant = 'light',
}: {
  brand: string
  logo?: string
  logoDark?: string
  className?: string
  variant?: 'light' | 'dark' | 'auto'
}) {
  const { getBrandByName } = useCatalog()

  let resolvedLogo = variant === 'dark' && logoDark ? logoDark : logo

  if (!resolvedLogo && brand) {
    const dynamicBrand = getBrandByName(brand)
    if (dynamicBrand && dynamicBrand.logo) {
      resolvedLogo = variant === 'dark' && dynamicBrand.logoDark ? dynamicBrand.logoDark : dynamicBrand.logo
    }
  }

  if (resolvedLogo) {
    return (
      <img
        src={resolvedLogo}
        alt={`${brand} logo`}
        className={`object-contain transition-transform duration-300 ${className}`}
        loading="lazy"
      />
    )
  }

  const normalized = Object.keys(brandImageMap).find((k) => k.toLowerCase() === brand.toLowerCase())
  const brandData = normalized ? brandImageMap[normalized] : null

  if (brandData) {
    const src = variant === 'dark' ? brandData.dark : brandData.light
    return (
      <img
        src={src}
        alt={brandData.alt}
        className={`object-contain transition-transform duration-300 ${className}`}
        loading="lazy"
      />
    )
  }

  const SvgFallback = normalized ? brandLogoMap[normalized] : null
  if (SvgFallback) {
    return <SvgFallback className={className} />
  }

  return (
    <span className={`font-display text-lg sm:text-xl font-black tracking-tight text-current uppercase ${className}`}>
      {brand}
    </span>
  )
}


